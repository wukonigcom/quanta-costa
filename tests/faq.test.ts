import { expect, test } from 'claude-code/testing'
import { bar, billingPeriod, duration, money, pace, tokenText, weeks } from '../hooks/register'

test('The worked examples in FAQ.md add up', () => {
  const now = Date.parse('2026-10-10T10:00:00Z')
  const p = billingPeriod(now, 29, 'Europe/Vienna')
  expect([p.daysGone, p.daysTotal, p.daysLeft]).toEqual([11, 30, 19])
  expect([weeks(p.daysGone), weeks(p.daysTotal), weeks(p.daysLeft)]).toEqual(['1.6', '4.3', '2.7'])
  expect([weeks(p.daysGone, 'de'), weeks(p.daysTotal, 'de'), weeks(p.daysLeft, 'de')]).toEqual(['1,6', '4,3', '2,7'])
  expect(bar(p.percentGone)).toBe('████░░░░░░░░')
  expect(bar(42)).toBe('█████░░░░░░░')
  expect(bar(60)).toBe('███████░░░░░')
  expect(bar(75)).toBe('█████████░░░')
  const week = { kind: 'seven_day', resetsAt: '2026-10-12T10:00:00Z' }
  const a = pace({ ...week, percentUsed: 42 }, now)
  expect(a?.isOnTrack).toBe(true)
  expect(((a!.runsOutAt - Date.parse('2026-10-05T10:00:00Z')) / 86400000).toFixed(1)).toBe('11.9')
  const b = pace({ ...week, percentUsed: 60 }, Date.parse('2026-10-07T10:00:00Z'))
  expect(b?.isOnTrack).toBe(false)
  expect(new Date(b!.runsOutAt).toISOString()).toBe('2026-10-08T18:00:00.000Z')
  expect(pace({ ...week, percentUsed: 1 }, now)).toBe(null)
  expect(pace({ ...week, percentUsed: 30 }, Date.parse('2026-10-05T12:00:00Z'))).toBe(null)
  expect(money(300, 'EUR', 0.89238)).toBe('€267.71')
  expect(money(180 / 0.89238, 'EUR', 0.89238)).toBe('€180.00')
  expect(money(4.95, 'EUR', 0.89238, 'de')).toBe('4,42 €')
  expect(money(0.07, 'EUR', 0.89238, 'de')).toBe('0,06 €')
  expect(money(300, 'EUR', 0.89238, 'de')).toBe('267,71 €')
  expect(tokenText(3_300_000)).toBe('3.3M')
  expect(tokenText(3_300_000, 'de')).toBe('3,3 Mio')
  expect(tokenText(85_000, 'de')).toBe('85 Tsd.')
  expect(duration(80 * 60000)).toBe('1h 20m')
  expect((300 / (180 / 0.89238)).toFixed(1)).toBe('1.5')
  const n = billingPeriod(Date.parse('2026-11-10T10:00:00Z'), 31, 'Europe/Vienna')
  expect([new Date(n.start).toISOString().slice(0, 10), new Date(n.end).toISOString().slice(0, 10)]).toEqual(['2026-10-31', '2026-11-30'])
  const d = billingPeriod(Date.parse('2026-12-10T10:00:00Z'), 31, 'Europe/Vienna')
  expect(new Date(d.end).toISOString().slice(0, 10)).toBe('2026-12-31')
})
